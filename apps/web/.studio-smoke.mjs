import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', e => errors.push(String(e)))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
const flat = async () => (await page.locator('body').innerText()).replace(/\n+/g, ' | ')
await page.goto(process.argv[2], { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
// Create a running session so the studio has a desk.
await page.getByPlaceholder('描述新会话要做的第一件事').fill('请执行 bash 命令 sleep 90 并等待，然后只回复：完成。')
await page.getByRole('button', { name: '新建会话并发送' }).click()
await page.waitForTimeout(9000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
await page.getByRole('button', { name: '工作室' }).click()
await page.waitForTimeout(2500)
let text = await flat()
console.log('STUDIO:', text.includes('工作室'), text.includes('点击工位跟随该会话'))
console.log('DESK-ACTIVITY:', text.includes('后台作业') || text.includes('对话轮次'))
await page.screenshot({ path: '/tmp/studio-floor.png' })
// Click the running desk to follow it.
const desk = page.getByRole('button', { name: /sleep 90/ }).first()
console.log('DESK-COUNT:', await desk.count())
if (await desk.count() > 0) {
  await desk.click()
  await page.waitForTimeout(2500)
  text = await flat()
  console.log('FOCUS-FROM-DESK:', text.includes('返回总览'), text.includes('开始观察后的变化'))
  await page.getByRole('button', { name: '返回总览' }).click()
  await page.waitForTimeout(1500)
}
// Toggle back to canvas and verify the preference survives a reload.
await page.getByRole('button', { name: '画布' }).click()
await page.waitForTimeout(1500)
await page.reload({ waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
text = await flat()
console.log('PREF-CANVAS-AFTER-RELOAD:', text.includes('其他会话'))
await page.screenshot({ path: '/tmp/canvas-after-toggle.png' })
console.log('ERRORS:', errors.slice(0, 4))
await browser.close()
