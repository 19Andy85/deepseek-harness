import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'no-preference' })
const errors = []
page.on('pageerror', e => errors.push(String(e)))
const flat = async () => (await page.locator('body').innerText()).replace(/\n+/g, ' | ')
await page.goto(process.argv[2], { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
await page.getByPlaceholder('描述新会话要做的第一件事').fill('请执行 bash 命令 sleep 60 并等待，然后只回复：完成。')
await page.getByRole('button', { name: '新建会话并发送' }).click()
await page.waitForTimeout(9000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
await page.getByRole('button', { name: '工作室' }).click()
await page.waitForTimeout(2500)
const runningDesk = page.locator('button[aria-label*="运行中"]').first()
console.log('RUNNING-DESK:', await runningDesk.count())
const animations = await runningDesk.evaluate(el => [...el.querySelectorAll('*')]
  .map(node => getComputedStyle(node).animationName)
  .filter(name => name !== 'none'))
console.log('ANIMATIONS:', JSON.stringify(animations))
const text = await flat()
console.log('STUDIO-LABELS:', text.includes('工作室'), text.includes('点击工位跟随该会话'))
await page.screenshot({ path: '/tmp/vs2-studio.png' })
console.log('ERRORS:', errors.slice(0, 3))
await browser.close()
