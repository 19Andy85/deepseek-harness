import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', e => errors.push(String(e)))
await page.goto(process.argv[2], { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
await page.getByPlaceholder('描述新会话要做的第一件事').fill('请执行 bash 命令 sleep 120 并等待，然后只回复：完成。')
await page.getByRole('button', { name: '新建会话并发送' }).click()
await page.waitForTimeout(9000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
await page.getByRole('button', { name: '工作室' }).click()
await page.waitForTimeout(1500)
const card = page.locator('[class*="teamCard"]').first()
if (await card.count() > 0) await card.click()
await page.waitForTimeout(1500)
await page.screenshot({ path: '/tmp/r3-desktop.png' })
console.log('DESKTOP-OVERFLOW:', await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth))
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForTimeout(1500)
await page.screenshot({ path: '/tmp/r3-narrow.png' })
console.log('NARROW-OVERFLOW:', await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth))
console.log('ERRORS:', errors.slice(0, 3))
await browser.close()
