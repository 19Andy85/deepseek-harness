import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', e => errors.push(String(e)))
const flat = async () => (await page.locator('body').innerText()).replace(/\n+/g, ' | ')
await page.goto(process.argv[2], { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
await page.getByPlaceholder('描述新会话要做的第一件事').fill('请立即使用 subagent 工具派一个子代理执行 bash 命令 sleep 60 并等待；然后等待子代理完成并只回复：父完成。不要做其他事。')
await page.getByRole('button', { name: '新建会话并发送' }).click()
await page.waitForTimeout(18000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(4000)
let text = await flat()
console.log('DERIVED:', text.includes('派生自'))
console.log('SUBAGENT-TRACK:', text.includes('子代理'))
console.log('TAIL:', text.slice(-700))
await page.screenshot({ path: '/tmp/vf3-derived.png' })
console.log('ERRORS:', errors.slice(0, 3))
await browser.close()
