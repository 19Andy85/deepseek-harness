import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', e => errors.push(String(e)))
await page.goto(process.argv[2], { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
await page.locator('#project-console-workspace').selectOption({ label: 'suhui' })
await page.waitForTimeout(2500)
const text = (await page.locator('body').innerText()).replace(/\n+/g, ' | ')
console.log('EMPTY-TITLE:', text.includes('还没有活跃会话'))
console.log('EMPTY-HINT:', text.includes('派发给数字伙伴'))
await page.screenshot({ path: '/tmp/audit-empty-fixed.png' })
await page.emulateMedia({ colorScheme: 'light' })
await page.waitForTimeout(800)
await page.screenshot({ path: '/tmp/audit-empty-fixed-light.png' })
await page.emulateMedia({ colorScheme: 'dark' })
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForTimeout(800)
await page.screenshot({ path: '/tmp/audit-empty-fixed-narrow.png', fullPage: true })
console.log('ERRORS:', errors.slice(0, 3))
await browser.close()
