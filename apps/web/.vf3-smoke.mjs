import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', e => errors.push(String(e)))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
const flat = async () => (await page.locator('body').innerText()).replace(/\n+/g, ' | ')
await page.goto(process.argv[2], { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
// A running session with a background job.
await page.getByPlaceholder('描述新会话要做的第一件事').fill('请执行 bash 命令 sleep 90 并等待，然后只回复：完成。')
await page.getByRole('button', { name: '新建会话并发送' }).click()
await page.waitForTimeout(8000)
// A session that delegates to a subagent, to exercise the derivation marker.
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2000)
await page.getByPlaceholder('描述新会话要做的第一件事').fill('请使用 subagent 工具派一个子代理去读取 README.md 的第一行，然后等待它完成并只回复：父完成。')
await page.getByRole('button', { name: '新建会话并发送' }).click()
await page.waitForTimeout(25000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(4000)
let text = await flat()
console.log('TRACKS:', text.includes('后台作业') || text.includes('对话轮次'))
console.log('DERIVED:', text.includes('派生自'))
console.log('BODY-TAIL:', text.slice(-900))
await page.screenshot({ path: '/tmp/vf3-lanes.png' })
console.log('ERRORS:', errors.slice(0, 4))
await browser.close()
