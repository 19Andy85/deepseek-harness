import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome' })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', e => errors.push(String(e)))
page.on('console', m => { if (m.type() === 'error' && !m.text().includes('deepseek-account')) errors.push(m.text()) })
await page.goto(process.argv[2], { waitUntil: 'domcontentloaded' })
await page.waitForTimeout(6000)
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(2500)
await page.screenshot({ path: '/tmp/audit-empty-dark.png' })
// A slow running session with a job.
await page.getByPlaceholder('描述新会话要做的第一件事').fill('请执行 bash 命令 sleep 120 并等待，然后只回复：完成。')
await page.getByRole('button', { name: '新建会话并发送' }).click()
await page.waitForTimeout(9000)
// A session that asks for a plan review, so the inbox has a waiting item.
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(1500)
await page.getByPlaceholder('描述新会话要做的第一件事').fill('请只回复：等待审批检查。不要使用任何工具。')
await page.getByRole('button', { name: '新建会话并发送' }).click()
await page.waitForTimeout(8000)
const editor = page.locator('[contenteditable="true"]').first()
await editor.click()
await page.keyboard.type('/plan 请立即调用 exit_plan_mode 工具。plan 必须严格以 "# Plan" 开头，内容为 "- 视觉审查计划"；不要修改任何文件。')
await page.keyboard.press('Enter')
await page.waitForTimeout(6000)
for (let i = 0; i < 24; i += 1) {
  await page.waitForTimeout(3000)
  const body = await page.locator('body').innerText()
  if (body.includes('Approve') || body.includes('计划待审')) break
}
await page.getByText('项目控制台').first().click()
await page.waitForTimeout(4000)
await page.screenshot({ path: '/tmp/audit-inbox-dark.png' })
await page.getByRole('button', { name: '工作室' }).click()
await page.waitForTimeout(2500)
await page.screenshot({ path: '/tmp/audit-studio-dark.png' })
await page.emulateMedia({ colorScheme: 'light' })
await page.waitForTimeout(1000)
await page.screenshot({ path: '/tmp/audit-studio-light.png' })
await page.getByRole('button', { name: '画布' }).click()
await page.waitForTimeout(1500)
await page.screenshot({ path: '/tmp/audit-canvas-light.png' })
await page.emulateMedia({ colorScheme: 'dark' })
await page.waitForTimeout(800)
const running = page.locator('article').filter({ hasText: 'sleep 120' }).first()
if (await running.count() > 0) {
  await running.getByRole('button', { name: '聚焦会话' }).click()
  await page.waitForTimeout(3000)
  await page.screenshot({ path: '/tmp/audit-focus-dark.png' })
  await page.getByRole('button', { name: '返回总览' }).click()
  await page.waitForTimeout(1500)
}
await page.setViewportSize({ width: 390, height: 844 })
await page.waitForTimeout(1000)
await page.screenshot({ path: '/tmp/audit-narrow-dark.png', fullPage: true })
console.log('ERRORS:', errors.slice(0, 5))
await browser.close()
